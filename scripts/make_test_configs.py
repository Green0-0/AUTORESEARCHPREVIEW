"""Generate the test-run configs (plan §9.3): 4 test tasks x 2 arms x 2 seeds, 24 h, frozen judge.

One pipeline job per task: optimized s1+s2 on replica :8000, naive (uniform) s1+s2 on :8001, so both arms get
equal compute on the same node. Judge settings and the calibration (a, b) come from the frozen judge study.

usage: python scripts/make_test_configs.py --strategy basic_k --k 5 --anchor-facts [--cal-a 0 --cal-b 1] [--hours 24]
       then, per task:  sbatch -t 25:00:00 slurm/pipeline.sbatch configs/test/<task>_*.yaml
"""
import argparse
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
TEST = ["t18_anytime", "t09_tokenizer_transfer", "t13_robust_noadv", "t16_synthetic_data"]
SHORT = {t: t.split("_")[0] for t in TEST}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--strategy", required=True)
    ap.add_argument("--k", type=int, default=5)
    ap.add_argument("--anchor-facts", action="store_true")
    ap.add_argument("--fewshot-source", default="surrogate")
    ap.add_argument("--cal-a", type=float, default=0.0, help="identity by default (plan §9.6)")
    ap.add_argument("--cal-b", type=float, default=1.0)
    ap.add_argument("--hours", type=float, default=24.0)
    ap.add_argument("--max-inflight", type=int, default=12, help="per run; 2 runs share each replica")
    ap.add_argument("--max-backlog", type=int, default=60, help="ideation backpressure (unscored ideas); 2026-11-11")
    ap.add_argument("--ideation-max-tokens", type=int, default=8000, help="t18 truncated 18-23%% at 6000")
    ap.add_argument("--out", default=str(REPO / "configs" / "test"))
    a = ap.parse_args()
    base = yaml.safe_load((REPO / "configs" / "train_s3" / "t07_optimized_s3.yaml").read_text())
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for task in TEST:
        for arm in ("optimized", "naive"):
            for seed in (1, 2):
                c = {k: v for k, v in base.items() if k not in ("run_id", "task_id", "arm", "seed", "sampler", "stop")}
                c["run_id"] = f"test_{SHORT[task]}_{arm}_s{seed}"
                c["task_id"] = task
                c["arm"] = arm
                c["seed"] = 100 + seed
                c["llm"] = dict(base["llm"], base_url=f"http://127.0.0.1:{8000 if arm == 'optimized' else 8001}/v1",
                                max_inflight=a.max_inflight)
                c["llm"]["purposes"] = {k: dict(v) for k, v in base["llm"]["purposes"].items()}
                c["llm"]["purposes"]["ideation"]["max_tokens"] = a.ideation_max_tokens
                c["ideation"] = dict(base.get("ideation") or {}, max_backlog=a.max_backlog)
                c["sampler"] = {"mode": "thompson" if arm == "optimized" else "uniform"}
                c["judge"] = {"strategy": a.strategy, "k": a.k, "anchor_facts": a.anchor_facts,
                              "fewshot_source": a.fewshot_source}
                c["scoring"] = {"calibration": {"a": a.cal_a, "b": a.cal_b}}
                c["stop"] = {"max_hours": a.hours, "max_ideas": None}
                p = out / f"{SHORT[task]}_{arm}_s{seed}.yaml"
                p.write_text("# Test run v2 (plan §9.3; rerun after the tagging overflow, 2026-11-11), generated by scripts/make_test_configs.py with the FROZEN judge.\n"
                             + yaml.safe_dump(c, sort_keys=False))
                print(p)


if __name__ == "__main__":
    main()
